function validateDocManifest(manifest) {
  if (manifest?.schemaVersion !== 1 || manifest?.generator !== 'scripts/fetch-doc-sources.mjs') {
    throw new Error('invalid documentation source manifest')
  }
  if (JSON.stringify(manifest.catalog?.ids) !== JSON.stringify(expectedCatalogIds)) {
    throw new Error('documentation source catalog does not match the expected public catalog')
  }
  const ids = manifest.products?.map((entry) => entry.id)
  const expected = productSpecs.filter((spec) => spec.docOnly || spec.docSupplement).map((spec) => spec.id).sort(ascii)
  if (!Array.isArray(ids) || JSON.stringify([...ids].sort(ascii)) !== JSON.stringify(expected)) {
    throw new Error(`documentation source products must be exactly: ${expected.join(', ')}`)
  }
}

async function readDocSources() {
  const manifestPath = join(docSourceDir, 'manifest.json')
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8'))
  validateDocManifest(manifest)
  const docPackageOwners = new Map()
  for (const productManifest of manifest.products) {
    const packageNames = new Set([
      productManifest.sourcePackage,
      ...productManifest.releasePackages.map((entry) => entry.name),
    ])
    for (const packageName of packageNames) {
      const previousOwner = docPackageOwners.get(packageName)
      if (previousOwner && previousOwner !== productManifest.id) {
        throw new Error(`documentation package ${packageName} belongs to both ${previousOwner} and ${productManifest.id}`)
      }
      docPackageOwners.set(packageName, productManifest.id)
    }
  }
  const byProduct = new Map()
  for (const productManifest of manifest.products) {
    const productRoot = join(docSourceDir, 'products', productManifest.id)
    const sources = []
    for (const document of productManifest.documents) {
      const file = join(productRoot, ...document.sourcePath.split('/'))
      const bytes = await readFile(file)
      if (sha256(bytes) !== document.sha256) {
        throw new Error(`documentation hash mismatch: ${document.sourcePath}`)
      }
      const text = normalizeText(bytes.toString('utf8'))
      sources.push({
        kind: 'document',
        id: `${productManifest.id}:${document.sourcePath}`,
        name: document.sourcePath,
        directory: productRoot,
        file,
        body: stripDocumentFrontmatter(text),
        description: '',
        license: 'MIT',
        productId: productManifest.id,
        supplemental: false,
        frameworks: document.frameworks || [],
        outputPath: document.outputPath,
        sourcePath: document.sourcePath,
        packageName: document.sourcePackage || productManifest.sourcePackage,
        packageVersion: productManifest.releasePackages.find((entry) => entry.name === (document.sourcePackage || productManifest.sourcePackage))?.version || '',
        sourceCommit: document.sourceCommit || productManifest.commit,
        sourceRef: `github:${productManifest.repository}@${document.sourceCommit || productManifest.commit}#${document.sourcePath}`,
        sha256: document.sha256,
        document,
        productManifest,
      })
    }
    byProduct.set(productManifest.id, { manifest: productManifest, sources, productRoot })
  }
  return { manifest, byProduct, docPackageOwners }
}

function stripDocumentFrontmatter(text) {
  const match = text.match(/^---\n[\s\S]*?\n---(?:\n|$)/)
  return normalizeText(match ? text.slice(match[0].length) : text)
}

function parseJsonArray(value, label) {
  if (!value) return []
  let parsed
  try {
    parsed = JSON.parse(value)
  } catch {
    throw new Error(`${label} is not valid JSON`)
  }
  if (!Array.isArray(parsed) || parsed.some((entry) => typeof entry !== 'string')) {
    throw new Error(`${label} must be an array of strings`)
  }
  return parsed
}

