function splitH2(body) {
  const lines = normalizeText(body).trimEnd().split('\n')
  if (lines[0]?.startsWith('# ') && !lines[0].startsWith('## ')) {
    lines.shift()
    while (lines[0] === '') lines.shift()
  }
  const blocks = []
  let heading = 'Overview'
  let content = []
  let fence = null
  const flush = () => {
    const value = normalizeText(content.join('\n')).trim()
    if (value) blocks.push({ heading, content: `${value}\n` })
    content = []
  }
  for (const line of lines) {
    const fenceMatch = line.match(/^\s*(```+|~~~+)/)
    if (fenceMatch) {
      const marker = fenceMatch[1]
      if (!fence) fence = { character: marker[0], length: marker.length }
      else if (fence.character === marker[0] && marker.length >= fence.length) fence = null
      content.push(line)
      continue
    }
    const h2 = !fence && line.match(/^##\s+(.+?)\s*$/)
    if (h2) {
      flush()
      heading = h2[1]
      continue
    }
    content.push(line)
  }
  flush()
  return blocks
}

