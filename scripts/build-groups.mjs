function titleCase(value) {
  return value
    .split(/[-_/]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join(' ')
}

function sha256(value) {
  return createHash('sha256').update(value).digest('hex')
}

function normalizeText(value) {
  const text = value.replace(/\r\n?/g, '\n').replace(/[ \t]+$/gm, '')
  return `${text.replace(/\s+$/, '')}\n`
}

function json(value) {
  return `${JSON.stringify(value, null, 2)}\n`
}

async function exists(path) {
  try {
    await lstat(path)
    return true
  } catch (error) {
    if (error?.code === 'ENOENT') return false
    throw error
  }
}

async function walk(path) {
  const entries = (await readdir(path, { withFileTypes: true })).sort((a, b) => ascii(a.name, b.name))
  const files = []
  for (const entry of entries) {
    const child = join(path, entry.name)
    if (entry.isDirectory()) files.push(...(await walk(child)))
    else if (entry.isFile()) files.push(child)
    else throw new Error(`unsupported filesystem entry: ${child}`)
  }
  return files
}

function decodeYamlScalar(raw) {
  const value = raw.trim()
  if (value.startsWith('"')) return JSON.parse(value)
  if (value.startsWith("'")) return value.slice(1, -1).replace(/''/g, "'")
  return value
}

function parseFrontmatter(text, path) {
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/)
  if (!match) throw new Error(`missing frontmatter: ${path}`)
  const fields = new Map()
  const metadata = new Map()
  let inMetadata = false
  for (const line of match[1].split(/\r?\n/)) {
    if (line === 'metadata:') {
      inMetadata = true
      continue
    }
    const field = line.match(inMetadata ? /^  ([a-z0-9-]+):\s*(.*)$/ : /^([a-z0-9-]+):\s*(.*)$/)
    if (!field) continue
    ;(inMetadata ? metadata : fields).set(field[1], decodeYamlScalar(field[2]))
  }
  const name = fields.get('name')
  const description = fields.get('description')
  if (!name || !description) throw new Error(`missing name or description: ${path}`)
  return {
    name,
    description,
    license: fields.get('license') || '',
    metadata,
    body: normalizeText(text.slice(match[0].length)),
  }
}

function readExportedNames(text) {
  const names = []
  for (const line of text.split(/\r?\n/)) {
    if (!line || line.startsWith('#') || line.startsWith('package\t')) continue
    const fields = line.split('\t')
    if (fields.length !== 6) throw new Error(`invalid exporter manifest row: ${line}`)
    for (const name of fields[5].split(',').filter(Boolean)) names.push(name)
  }
  if (!names.length || new Set(names).size !== names.length) {
    throw new Error('exporter manifest has no skills or duplicate output names')
  }
  return names.sort(ascii)
}

