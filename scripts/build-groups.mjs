async function collectAtomicAssetMap(spec, sources, outputDir) {
  const map = new Map()
  for (const source of sources.filter((entry) => entry.kind === 'atomic')) {
    const referenceDir = join(source.directory, 'references')
    if (!(await exists(referenceDir))) continue
    for (const file of await walk(referenceDir)) {
      const rel = relative(source.directory, file).split(sep).join('/')
      if (rel === 'references/INTENT-SKILL-MAP.md') continue
      const targetRel = `references/assets/${source.name}/${rel}`
      const target = join(outputDir, ...targetRel.split('/'))
      await mkdir(dirname(target), { recursive: true })
      await copyFile(file, target)
      map.set(resolve(file), targetRel)
    }
  }
  return map
}

async function collectDocAssetMap(docBundle, outputDir) {
  const map = new Map()
  if (!docBundle) return map
  for (const asset of docBundle.manifest.assets || []) {
    const source = join(docBundle.productRoot, ...asset.sourcePath.split('/'))
    const targetRel = `references/doc-assets/${asset.outputPath}`
    const target = join(outputDir, ...targetRel.split('/'))
    const bytes = await readFile(source)
    if (sha256(bytes) !== asset.sha256) throw new Error(`documentation asset hash mismatch: ${asset.sourcePath}`)
    await mkdir(dirname(target), { recursive: true })
    await writeFile(target, bytes)
    map.set(posix.normalize(asset.sourcePath), targetRel)
    map.set(posix.normalize(asset.outputPath), targetRel)
    map.set(posix.normalize(posix.join('docs', asset.outputPath)), targetRel)
  }
  return map
}

function rewriteLinks(text, context) {
  const rewriteLine = (line) => line.replace(/\]\(([^)]+)\)/g, (match, rawTarget, offset) => {
    if (isInsideInlineCode(line, offset)) return match
    const wrapped = rawTarget.trim()
    const targetValue = wrapped.startsWith('<') && wrapped.endsWith('>') ? wrapped.slice(1, -1) : wrapped
    const liveGithub = targetValue.match(/^https:\/\/github\.com\/([^/]+\/[^/]+)\/(?:blob|tree)\/(?:main|master)\/([^#?]+)([?#].*)?$/i)
    if (liveGithub && context.source.sourceDocuments?.includes(`${liveGithub[1]}:${liveGithub[2]}`)) {
      const output = context.sourceOutputMap.get(context.source.id)
      if (!output) throw new Error(`source document link has no bundled output: ${context.source.id}`)
      return `](${relativeLink(context.outputFile, output.file)}#${output.anchor})`
    }
    const pinned = pinMutableRepositoryRefs(targetValue, gitSource(context.source))
    if (pinned !== targetValue) return `](${pinned})`
    const parts = targetValue.match(/^([^#?]*)([?#].*)?$/)
    if (!parts) return match
    let target = parts[1]
    const suffix = parts[2] || ''
    if (!target && suffix.startsWith('#')) {
      const output = context.sourceOutputMap.get(context.source.id)
      return `](${relativeLink(context.outputFile, output.file)}${suffix})`
    }
    if (!target || /^(?:[a-z]+:|#)/i.test(target)) return match
    if (target.startsWith('/')) {
      return context.source.kind === 'document' ? `](https://tanstack.com${target}${suffix})` : match
    }
    try {
      target = decodeURIComponent(target)
    } catch {
      throw new Error(`invalid encoded link in ${context.source.id}: ${rawTarget}`)
    }

    if (context.source.kind === 'atomic') {
      const absolute = resolve(dirname(context.source.skillPath), target)
      const localAsset = context.atomicAssetMap.get(absolute)
      if (localAsset) return `](${relativeLink(context.outputFile, join(context.productDir, ...localAsset.split('/')))}${suffix})`
      const targetSource = resolveAtomicTarget(target, context)
      if (targetSource) return `](${atomicTargetDestination(targetSource, context)}${suffix.startsWith('#') ? '' : suffix})`
      if (/SKILL\.md$/i.test(target)) {
        const origin = context.atomicOriginById.get(context.source.id)
        const resolvedOrigin = origin && posix.normalize(posix.join(posix.dirname(origin), target))
        throw new Error(`unresolved atomic skill link in ${context.source.id}: ${target} (resolved ${resolvedOrigin || 'unknown'})`)
      }
      return match
    }

    const resolvedSourcePath = posix.normalize(posix.join(posix.dirname(context.source.sourcePath), target))
    const targetSource = context.docPathMap.get(resolvedSourcePath)
    if (targetSource && context.sourceOutputMap.has(targetSource.id)) {
      const output = context.sourceOutputMap.get(targetSource.id)
      return `](${relativeLink(context.outputFile, output.file)}#${output.anchor}${suffix.startsWith('#') ? '' : suffix})`
    }
    const localAsset = context.docAssetMap.get(resolvedSourcePath)
    if (localAsset) return `](${relativeLink(context.outputFile, join(context.productDir, ...localAsset.split('/')))}${suffix})`
    const repo = context.source.productManifest.repository
    const commit = context.source.sourceCommit || context.source.productManifest.commit
    return `](https://github.com/${repo}/blob/${commit}/${resolvedSourcePath}${suffix})`
  })
  let fence = null
  return text.split('\n').map((line) => {
    const fenceMatch = line.match(/^\s*(```+|~~~+)/)
    if (fenceMatch) {
      const marker = fenceMatch[1]
      if (!fence) fence = { character: marker[0], length: marker.length }
      else if (fence.character === marker[0] && marker.length >= fence.length) fence = null
      return line
    }
    return fence ? line : pinMutableRepositoryRefsInLine(rewriteAtomicLiteralSkillPaths(rewriteLine(line), context), context.source)
  }).join('\n')
}

function isInsideInlineCode(line, index) {
  let delimiterLength = 0
  for (const match of line.slice(0, index).matchAll(/`+/g)) {
    if (!delimiterLength) delimiterLength = match[0].length
    else if (match[0].length === delimiterLength) delimiterLength = 0
  }
  return delimiterLength > 0
}

function resolveAtomicTarget(target, context) {
  const absolute = resolve(dirname(context.source.skillPath), target)
  const direct = context.atomicFileMap.get(absolute)
  if (direct) return direct
  const origin = context.atomicOriginById.get(context.source.id)
  const resolvedOrigin = origin && posix.normalize(posix.join(posix.dirname(origin), target))
  const candidates = [
    resolvedOrigin,
    posix.normalize(target),
    posix.normalize(target.replace(/^node_modules\/@tanstack\//, 'packages/')),
  ].filter(Boolean)
  for (const candidate of candidates) {
    const source = context.atomicOriginMap.get(candidate)
    if (source) return source
  }
  return undefined
}

function atomicTargetDestination(targetSource, context) {
  const output = context.sourceOutputMap.get(targetSource.id)
  if (output) return `${relativeLink(context.outputFile, output.file)}#${output.anchor}`
  if (targetSource.productId === context.source.productId) {
    throw new Error(`in-product atomic link was not bundled: ${context.source.id} -> ${targetSource.id}`)
  }
  return `https://skills.sh/lukasa1993/tanstack-skills-extracted/tanstack-${targetSource.productId}`
}

function rewriteAtomicLiteralSkillPaths(line, context) {
  if (context.source.kind !== 'atomic') return line
  const pattern = /(?:node_modules\/@tanstack\/[a-z0-9_@.*\/-]+|(?:\.\.\/)+[a-z0-9_@.*\/-]+|(?:ai-persistence|compositions)\/[a-z0-9_@.*\/-]+)\/SKILL\.md/gi
  return line.replace(pattern, (target) => {
    if (target.includes('*') && context.source.productId === 'ai' && target.startsWith('ai-persistence/')) {
      return relativeLink(context.outputFile, join(context.productDir, 'references', 'persistence-adapters.md'))
    }
    const targetSource = resolveAtomicTarget(target, context)
    if (!targetSource) throw new Error(`unresolved literal atomic skill path in ${context.source.id}: ${target}`)
    return atomicTargetDestination(targetSource, context)
  })
}

function gitSource(source) {
  if (source.productManifest && source.sourceCommit) {
    return { repository: source.productManifest.repository, commit: source.sourceCommit }
  }
  const match = source.sourceRef?.match(/^github:([^@]+)@([0-9a-f]{40})#/i)
  return match ? { repository: match[1], commit: match[2] } : null
}

function pinMutableRepositoryRefs(value, sourceGit) {
  if (!sourceGit) return value
  const escapedRepo = sourceGit.repository.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  const patterns = [
    new RegExp(`(https://github\\.com/${escapedRepo}/(?:blob|tree)/)(?:main|master)(?=/|[?#]|$)`, 'gi'),
    new RegExp(`(https://raw\\.githubusercontent\\.com/${escapedRepo}/)(?:main|master)(?=/|[?#]|$)`, 'gi'),
    new RegExp(`(https://(?:codesandbox\\.io/s/|stackblitz\\.com/)github/${escapedRepo}/(?:blob|tree)/)(?:main|master)(?=/|[?#]|$)`, 'gi'),
  ]
  return patterns.reduce((result, pattern) => result.replace(pattern, `$1${sourceGit.commit}`), value)
}

function pinMutableRepositoryRefsInLine(line, source) {
  const sourceGit = gitSource(source)
  if (!sourceGit) return line
  return line.replace(/https:\/\/[^\s<>"'`)]+/gi, (url, offset) =>
    isInsideInlineCode(line, offset) ? url : pinMutableRepositoryRefs(url, sourceGit))
}

function containsMutableRepositoryRef(value) {
  return [
    /https:\/\/github\.com\/[^/\s]+\/[^/\s]+\/(?:blob|tree)\/(?:main|master)(?=\/|[?#]|$)/i,
    /https:\/\/raw\.githubusercontent\.com\/[^/\s]+\/[^/\s]+\/(?:main|master)(?=\/|[?#]|$)/i,
    /https:\/\/(?:codesandbox\.io\/s\/|stackblitz\.com\/)github\/[^/\s]+\/[^/\s]+\/(?:blob|tree)\/(?:main|master)(?=\/|[?#]|$)/i,
  ].some((pattern) => pattern.test(value))
}

function relativeLink(fromFile, toFile) {
  let value = relative(dirname(fromFile), toFile).split(sep).join('/')
  if (!value.startsWith('.')) value = `./${value}`
  return value
}

function documentationFrameworks(spec, docManifest) {
  if (!docManifest?.frameworks?.length && !docManifest?.experimentalFrameworks?.length) return []
  const corePackages = {
    charts: '@tanstack/charts',
    form: '@tanstack/form-core',
    hotkeys: '@tanstack/hotkeys',
    pacer: '@tanstack/pacer',
    store: '@tanstack/store',
    virtual: '@tanstack/virtual-core',
  }
  const experimental = new Set(docManifest.experimentalFrameworks || [])
  const frameworks = [...new Set([...(docManifest.frameworks || []), ...experimental])]
  return frameworks.map((framework) => {
    if (framework === 'vanilla') return [framework, corePackages[spec.id], false]
    if (spec.id === 'charts' && framework === 'react-native') {
      return [framework, '@tanstack/react-native-charts', experimental.has(framework)]
    }
    if (spec.id === 'charts') return [framework, `@tanstack/charts/${framework}`, experimental.has(framework)]
    return [framework, `@tanstack/${framework}-${spec.id}`, experimental.has(framework)]
  })
}

function frameworkReference(spec, themes, framework, foundationTheme) {
  const mappedKey = spec.frameworkThemeMap?.[framework] || spec.frameworkDefaultTheme
  return themes.find((entry) => entry.key === `framework-${framework}`)
    || (mappedKey ? themes.find((entry) => entry.key === mappedKey) : undefined)
    || themes.find((entry) => entry.key === 'frameworks' || entry.key === 'frameworks-ui')
    || (framework === 'vanilla' ? foundationTheme : undefined)
}

function buildRootSkill(spec, themes, sourceCount, docManifest, routes) {
  const frameworkRoutes = spec.frameworks || documentationFrameworks(spec, docManifest)
  const foundationTheme = themes.find((entry) => ['foundations', 'getting-started'].includes(entry.key))
  const hasFrameworkReference = frameworkRoutes.some(([framework]) => frameworkReference(spec, themes, framework, foundationTheme))
  let workflowStep2 = '2. Choose the task reference that matches the requested outcome.'
  if (foundationTheme && hasFrameworkReference) workflowStep2 = '2. Read the foundation reference and the adapter reference for the detected framework.'
  else if (foundationTheme) workflowStep2 = '2. Read the foundation reference before the task-specific reference.'
  else if (hasFrameworkReference) workflowStep2 = '2. Read the adapter reference for the detected framework when the task uses an adapter.'
  if (spec.id === 'query') workflowStep2 = '2. Open the installed adapter’s index or a common task below. Use draft task guides as supplementary guidance after checking their APIs against the release-matched adapter.'
  const lines = [
    '---',
    `name: ${spec.name}`,
    `description: ${JSON.stringify(`${spec.description} Use when a project uses ${spec.title} or when the task needs its setup, implementation, debugging, testing, migration, or integration guidance.`)}`,
    'license: MIT',
    'metadata:',
    '  tanstack-curation: "thematic-product"',
    `  tanstack-source-count: "${sourceCount}"`,
    '---',
    generatedComment,
    '',
    `# ${spec.title}`,
    '',
    spec.description,
    '',
  ]
  if (spec.maturity) lines.push('> ' + spec.maturity, '')
  lines.push(
    '## Workflow',
    '',
    '1. Inspect installed TanStack packages and exact versions.',
    workflowStep2,
    '3. Topic references are indexes. Choose one guide or section for the task; follow its prerequisite links only when needed.',
    '4. Prefer installed package types and version-matched source guidance over memory.',
    frameworkRoutes.length ? '5. Preserve headless/core behavior when translating examples to a framework adapter.' : '5. Validate the implementation with the project types and tests.',
    '',
    '## Task routing',
    '',
  )
  for (const entry of themes) {
    lines.push(`- [${entry.title}](references/${entry.key}.md) — ${entry.description}`)
  }
  if (spec.tasks?.length) {
    lines.push('', '## Common tasks', '')
    for (const [title, sourcePath] of spec.tasks) {
      const route = routes.find((entry) => entry.sourcePath === sourcePath)
      if (!route) throw new Error(`Missing task guide: ${spec.id}/${sourcePath}`)
      lines.push(`- [${title}](${route.file})`)
    }
  }
  if (frameworkRoutes.length) {
    lines.push('', '## Framework routing', '')
    for (const [framework, packageName, experimental] of frameworkRoutes) {
      const selectedTheme = frameworkReference(spec, themes, framework, foundationTheme)
      const link = selectedTheme ? ` Read [${selectedTheme.title}](references/${selectedTheme.key}.md).${selectedTheme.key === `framework-${framework}` ? '' : ' Shared guidance; check adapter-specific differences.'}` : ' No dedicated adapter guide is bundled; consult the installed package documentation.'
      lines.push(`- **${titleCase(framework)}** — detect \`${packageName}\`.${experimental ? ' Experimental adapter.' : ''}${link}`)
    }
    if (spec.frameworkNote) lines.push('', spec.frameworkNote)
  }
  if (spec.related?.length) {
    lines.push('', '## Product boundaries', '')
    lines.push(`Use these separate product skills when the task crosses their boundary: ${spec.related.map((name) => `\`${name}\``).join(', ')}.`)
  }
  if (docManifest) {
    const releases = docManifest.releasePackages.map((entry) => `${entry.name}@${entry.version}`).join(', ')
    lines.push('', '## Source status', '', `Official documentation from \`${docManifest.repository}\`, matched to these verified release inputs: ${releases}.`)
  }
  lines.push('', 'See [source provenance](references/SOURCES.md) for exact upstream inputs and deduplication records.', '')
  return lines.join('\n')
}

function buildOpenAiYaml(spec) {
  return [
    'interface:',
    `  display_name: ${JSON.stringify(spec.title)}`,
    `  short_description: ${JSON.stringify(`Task and framework guides for ${spec.title}`)}`,
    `  default_prompt: ${JSON.stringify(`Use $${spec.name} to implement this ${spec.title} task with the installed framework and package versions.`)}`,
    '',
  ].join('\n')
}

async function buildProduct(spec, primaryAtomic, atomicSkills, docSources, stageSkillsDir) {
  const ownAtomic = primaryAtomic.filter((source) => source.productId === spec.id)
  const supplemental = spec.supplementalAtomicMatch
    ? atomicSkills.filter((source) => spec.supplementalAtomicMatch(source.name)).map((source) => ({ ...source, supplemental: true }))
    : []
  const docs = docSources.byProduct.get(spec.id)
  const sources = [...ownAtomic, ...supplemental, ...(docs?.sources || [])]
    .sort((left, right) => sourcePriority(left) - sourcePriority(right) || ascii(left.id, right.id))
  if (!sources.length) throw new Error(`${spec.id} has no source material`)

  const themed = createThemeBuckets(spec)
  for (const source of sources) {
    const selected = selectTheme(spec, source, (fallback) => {
      process.stderr.write(
        `WARNING: ${source.id} has no curated theme in ${spec.id}; routing it to ${fallback.key}.\n`,
      )
    })
    themed.get(selected.key).sources.push(source)
  }
  const usedThemes = [...themed.values()].filter((entry) => entry.sources.length > 0)
  if (!usedThemes.length) throw new Error(`${spec.id} has no populated themes`)

  const productDir = join(stageSkillsDir, spec.name)
  await mkdir(join(productDir, 'references'), { recursive: true })
  const atomicAssetMap = await collectAtomicAssetMap(spec, sources, productDir)
  const docAssetMap = await collectDocAssetMap(docs, productDir)
  const atomicFileMap = new Map(atomicSkills.map((source) => [resolve(source.skillPath), source]))
  const atomicOriginById = new Map()
  const atomicOriginMap = new Map()
  const addAtomicOrigin = (origin, source) => {
    const normalized = posix.normalize(origin)
    const prior = atomicOriginMap.get(normalized)
    if (prior && prior.id !== source.id) throw new Error(`ambiguous atomic source path: ${normalized}`)
    atomicOriginMap.set(normalized, source)
  }
  for (const source of atomicSkills) {
    const packageDirectory = source.packageName.replace(/^@tanstack\//, '')
    const origin = posix.normalize(`packages/${packageDirectory}/skills/${source.sourcePath}/SKILL.md`)
    atomicOriginById.set(source.id, origin)
    addAtomicOrigin(origin, source)
    addAtomicOrigin(origin.replace(/^packages\//, ''), source)
    addAtomicOrigin(`packages/${packageDirectory}/skills/${packageDirectory}/${source.sourcePath}/SKILL.md`, source)
    addAtomicOrigin(`${packageDirectory}/skills/${packageDirectory}/${source.sourcePath}/SKILL.md`, source)
  }
  const atomicByPackage = Map.groupBy(atomicSkills, (source) => source.packageName)
  for (const [packageName, packageSources] of atomicByPackage) {
    const packageDirectory = packageName.replace(/^@tanstack\//, '')
    const roots = packageSources.filter((source) => source.metadata.get('tanstack-type') === 'core' && !source.sourcePath.includes('/'))
    for (const rootSource of roots) {
      for (const source of packageSources) {
        addAtomicOrigin(`packages/${packageDirectory}/skills/${rootSource.sourcePath}/${source.sourcePath}/SKILL.md`, source)
        addAtomicOrigin(`${packageDirectory}/skills/${rootSource.sourcePath}/${source.sourcePath}/SKILL.md`, source)
      }
    }
  }
  const atomicAliases = new Map([
    ['packages/react-router/skills/react-router/SKILL.md', 'tanstack-router-core'],
    ['packages/react-router/skills/compositions/router-query/SKILL.md', 'tanstack-query-intent-compositions-compose-query-with-t-d0bcdebe'],
    ['compositions/router-query/SKILL.md', 'tanstack-query-intent-compositions-compose-query-with-t-d0bcdebe'],
  ])
  const atomicByName = new Map(atomicSkills.map((source) => [source.name, source]))
  for (const [origin, name] of atomicAliases) {
    const source = atomicByName.get(name)
    if (!source) throw new Error(`missing atomic alias target: ${name}`)
    addAtomicOrigin(origin, source)
    addAtomicOrigin(origin.replace(/^packages\//, ''), source)
  }
  const docPathMap = new Map((docs?.sources || []).map((source) => [posix.normalize(source.sourcePath), source]))
  const sourceOutputMap = new Map()
  for (const entry of usedThemes) {
    for (const source of entry.sources) sourceOutputMap.set(source.id, { file: join(productDir, 'references', 'guides', `${guideId(source.id)}.md`), anchor: anchorFor(source), theme: entry.key })
  }

  const provenanceSources = []
  const duplicateDocuments = []
  const duplicateSections = []
  const routes = []
  await mkdir(join(productDir, 'references', 'guides'), { recursive: true })
  for (const entry of usedThemes) {
    const indexFile = join(productDir, 'references', `${entry.key}.md`)
    const indexLines = [`# ${entry.title}`, '', entry.description, '',
      'Choose the guide for the task. Each guide records its source and package version.', '',
      '| Guide | Source status | Package version |', '| --- | --- | --- |']
    const seenDocuments = new Map()
    const seenSections = new Map()
    for (const source of entry.sources) {
      const outputFile = sourceOutputMap.get(source.id).file
      const context = { source, outputFile, productDir, atomicAssetMap, docAssetMap,
        atomicFileMap, atomicOriginById, atomicOriginMap, docPathMap, sourceOutputMap }
      const sourceLink = relativeLink(indexFile, outputFile)
      indexLines.push(`| [${escapeTable(sourceLabel(source))}](${sourceLink}) | ${sourceStatus(source)} | \`${escapeTable(source.packageName)}@${escapeTable(source.packageVersion)}\` |`)
      const docHash = sha256(Buffer.from(normalizeText(source.body)))
      const priorDocument = seenDocuments.get(docHash)
      const kept = []
      if (priorDocument) {
        duplicateDocuments.push({ duplicate: source.id, canonical: priorDocument.id, theme: entry.key, sha256: docHash })
        kept.push({ heading: 'Canonical guidance', rewritten: true, content: `This source is an exact duplicate. Read [${sourceLabel(priorDocument)}](${relativeLink(outputFile, sourceOutputMap.get(priorDocument.id).file)}).\n` })
      } else {
        seenDocuments.set(docHash, source)
        for (const block of splitH2(source.body)) {
          const blockHash = sha256(Buffer.from(canonicalBlock(block)))
          const prior = seenSections.get(blockHash)
          if (prior) {
            duplicateSections.push({ duplicate: `${source.id}#${block.heading}`, canonical: `${prior.source.id}#${prior.block.heading}`, theme: entry.key, sha256: blockHash })
            const destination = relativeLink(outputFile, sourceOutputMap.get(prior.source.id).file)
            kept.push({ heading: block.heading, rewritten: true, content: `This section is an exact duplicate. Read [${prior.block.heading} in ${sourceLabel(prior.source)}](${destination}).\n` })
          } else {
            seenSections.set(blockHash, { source, block })
            kept.push(block)
          }
        }
      }
      const plan = planGuide(kept)
      const prerequisites = source.kind === 'atomic'
        ? parseJsonArray(source.metadata.get('tanstack-requires'), `prerequisites of ${source.id}`).map((id) => {
          const output = sourceOutputMap.get(id)
          return output ? { id, file: relative(productDir, output.file).split(sep).join('/') } : { id }
        }) : []
      const header = [
        `# ${sourceLabel(source)}`, '', `<a id="${anchorFor(source)}"></a>`, '',
        `${sourceStatus(source)} · \`${source.packageName}@${source.packageVersion}\`.`, '',
        ...(sourceStatus(source) === 'Draft guidance' ? ['This is unpublished draft guidance. Check APIs against the installed adapter and its release-matched documentation.', ''] : []),
        `[Topic index](${relativeLink(outputFile, indexFile)}) · [Source provenance](../SOURCES.md)`, '',
        ...prerequisites.filter((prerequisite) => prerequisite.file).map((prerequisite) => `Prerequisite: [${sourceLabel(sources.find((item) => item.id === prerequisite.id))}](${relativeLink(outputFile, join(productDir, prerequisite.file))}).`),
        ...(prerequisites.length ? [''] : []),
      ]
      const sourceExamples = []
      for (const example of examples.filter((item) => item.product === spec.id && item.sourcePath === source.sourcePath)) {
        const file = `references/examples/${example.file}`
        await mkdir(dirname(join(productDir, file)), { recursive: true })
        await copyFile(join(exampleDir, example.file), join(productDir, file))
        sourceExamples.push({ file, title: example.title, testedPackages: example.testedPackages })
        const tested = Object.entries(example.testedPackages).map(([name, version]) => `\`${name}@${version}\``).join(', ')
        header.push(`Runnable repository example: [${example.title}](${relativeLink(outputFile, join(productDir, file))}). Tested with ${tested}. This MIT-licensed example is maintained here; the official guidance follows.`, '')
      }
      const guideLines = [...header]
      const sectionRoutes = []
      if (plan.split) guideLines.push('## Choose a section', '', 'Read the overview or setup when it is a prerequisite, then the section needed for the task.', '')
      for (const page of plan.pages) {
        const pageFile = page.key ? outputFile.replace(/\.md$/, `--${page.key}.md`) : outputFile
        const pageLines = plan.split ? [`# ${sourceLabel(source)} — ${page.blocks[0].heading}`, '',
          `[Guide and prerequisites](${relativeLink(pageFile, outputFile)}) · ${sourceStatus(source)} · \`${source.packageName}@${source.packageVersion}\`.`, ''] : guideLines
        for (const block of page.blocks) {
          if (block.heading !== 'Overview') pageLines.push(`## ${block.heading}`, '')
          pageLines.push((block.rewritten ? block.content : rewriteLinks(block.content, { ...context, outputFile: pageFile })).trimEnd(), '')
        }
        const body = normalizeText(pageLines.join('\n'))
        if (plan.split) {
          await writeFile(pageFile, body)
          guideLines.push(`- [${page.blocks[0].heading}](${relativeLink(outputFile, pageFile)}) — ${Math.ceil(Buffer.byteLength(body) / 1024)} KiB`)
        }
        sectionRoutes.push({ title: page.blocks.map((block) => block.heading).join('; '), file: relative(productDir, pageFile).split(sep).join('/'), bytes: Buffer.byteLength(body) })
      }
      // Preserve original inbound fragments on split/duplicate guide entry points.
      if (plan.split || priorDocument) {
        guideLines.push('', '<!-- Original source anchors retained for inbound links. -->')
        for (const fragment of markdownHeadingFragments(source.body)) guideLines.push(`<a id="${fragment}"></a>`)
      }
      const guideBody = normalizeText(guideLines.join('\n'))
      await writeFile(outputFile, guideBody)
      routes.push({ id: source.id, title: sourceLabel(source), theme: entry.key, kind: source.kind,
        status: sourceStatus(source), frameworks: source.frameworks, package: source.packageName,
        version: source.packageVersion, file: relative(productDir, outputFile).split(sep).join('/'),
        sourcePath: source.sourcePath, bytes: Buffer.byteLength(guideBody), prerequisites, sections: sectionRoutes, examples: sourceExamples })
      provenanceSources.push(provenanceRecord(source, entry.key, priorDocument?.id || null))
    }
    await writeFile(indexFile, normalizeText(indexLines.join('\n')))
  }
  await writeFile(join(productDir, 'references', 'ROUTES.json'), json({ schemaVersion: 1, product: spec.id, guides: routes }))

  const licenseMap = new Map()
  const licenseInputs = []
  for (const source of sources.filter((entry) => entry.kind === 'atomic')) {
    const licenseFile = join(source.directory, 'LICENSE')
    if (await exists(licenseFile)) licenseInputs.push({ file: licenseFile, origin: source.id })
  }
  for (const license of docs?.manifest.licenses || []) {
    const licenseFile = join(docs.productRoot, ...license.outputPath.split('/'))
    licenseInputs.push({ file: licenseFile, origin: `${spec.id}:${license.sourcePath}`, expectedSha256: license.sha256 })
  }
  for (const input of licenseInputs) {
    const licenseFile = input.file
    const bytes = await readFile(licenseFile)
    const hash = sha256(bytes)
    if (input.expectedSha256 && input.expectedSha256 !== hash) throw new Error(`license hash mismatch: ${input.origin}`)
    if (!licenseMap.has(hash)) {
      const target = join(productDir, 'licenses', `${hash}.txt`)
      await mkdir(dirname(target), { recursive: true })
      await writeFile(target, bytes)
      licenseMap.set(hash, { path: relative(productDir, target).split(sep).join('/'), sources: [] })
    }
    licenseMap.get(hash).sources.push(input.origin)
  }
  await copyFile(join(root, 'LICENSE'), join(productDir, 'LICENSE'))

  const sourcesMarkdown = [
    '# Source provenance',
    '',
    '| Source | Kind | Theme | Package or repository | Version or commit | Deduplicated into |',
    '| --- | --- | --- | --- | --- | --- |',
    ...provenanceSources.map((source) =>
      `| \`${escapeTable(source.id)}\` | ${source.kind} | \`${source.theme}\` | \`${escapeTable(source.package || source.repository || '')}\` | \`${escapeTable(source.version || source.commit || '')}\` | ${source.duplicateOf ? `\`${escapeTable(source.duplicateOf)}\`` : ''} |`),
    '',
    `Exact duplicate documents replaced with canonical links: ${duplicateDocuments.length}. Exact duplicate H2 sections replaced with canonical links: ${duplicateSections.length}. No fuzzy deduplication is used.`,
    '',
  ]
  await writeFile(join(productDir, 'references', 'SOURCES.md'), sourcesMarkdown.join('\n'))

  const provenance = {
    schemaVersion: 1,
    generator,
    product: spec.id,
    sources: provenanceSources,
    duplicateDocuments,
    duplicateSections,
    licenses: [...licenseMap.entries()].sort(([left], [right]) => ascii(left, right)).map(([sha, value]) => ({ sha256: sha, path: value.path, sources: value.sources.sort(ascii) })),
    documentationVerification: docs ? {
      catalogSha256: docSources.manifest.catalog.sha256,
      verification: docSources.manifest.verification,
      repositoryArchives: docs.manifest.repositoryArchives,
      linkValidation: docs.manifest.linkValidation,
    } : undefined,
  }
  await writeFile(join(productDir, 'references', 'PROVENANCE.json'), json(provenance))
  await writeFile(join(productDir, 'SKILL.md'), buildRootSkill(spec, usedThemes, sources.length, docs?.manifest, routes))
  await mkdir(join(productDir, 'agents'), { recursive: true })
  await writeFile(join(productDir, 'agents', 'openai.yaml'), buildOpenAiYaml(spec))

  const marker = {
    generator,
    name: spec.name,
    product: spec.id,
    sourceCount: sources.length,
    themes: usedThemes.map((entry) => entry.key),
    guideCount: routes.length,
    largestGuideEntryBytes: Math.max(...routes.map((route) => route.bytes)),
    inputSha256: sha256(Buffer.from(json(provenance))),
  }
  await writeFile(join(productDir, productMarker), json(marker))
  await validateProduct(productDir, spec, usedThemes)
  return { spec, marker, themes: usedThemes }
}

function provenanceRecord(source, themeKey, duplicateOf) {
  return {
    id: source.id,
    kind: source.kind,
    theme: themeKey,
    package: source.packageName || undefined,
    version: source.packageVersion || undefined,
    repository: source.productManifest?.repository,
    commit: source.sourceCommit || source.productManifest?.commit,
    sourcePath: source.sourcePath,
    sha256: source.sha256,
    sourceKind: source.document?.sourceKind,
    verifiedCommits: source.document?.verifiedCommits,
    duplicateOf: duplicateOf || undefined,
  }
}

function escapeTable(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('`', '\\`')
}

function markdownHeadingFragments(text) {
  const fragments = new Set()
  const counts = new Map()
  let fence = null
  for (const line of text.split('\n')) {
    const fenceMatch = line.match(/^\s*(```+|~~~+)/)
    if (fenceMatch) {
      const marker = fenceMatch[1]
      if (!fence) fence = { character: marker[0], length: marker.length }
      else if (fence.character === marker[0] && marker.length >= fence.length) fence = null
      continue
    }
    if (fence) continue
    const heading = line.match(/^\s{0,3}#{1,6}\s+(.+?)\s*#*\s*$/)
    if (!heading) continue
    const base = heading[1]
      .replace(/<[^>]*>/g, '')
      .normalize('NFKD')
      .replace(/\p{Diacritic}/gu, '')
      .toLowerCase()
      .replace(/[^\p{Letter}\p{Number}\s-]/gu, '')
      .trim()
      .replace(/\s+/gu, '-')
    if (!base) continue
    const occurrence = counts.get(base) || 0
    counts.set(base, occurrence + 1)
    fragments.add(occurrence ? `${base}-${occurrence}` : base)
  }
  return fragments
}

function hasMarkdownFragment(text, fragment) {
  const escaped = fragment.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  if (new RegExp(`<a\\s+id=["']${escaped}["']`, 'i').test(text)) return true
  return markdownHeadingFragments(text).has(fragment)
}

async function validateProduct(directory, spec, themes) {
  const rootSkill = join(directory, 'SKILL.md')
  const text = await readFile(rootSkill, 'utf8')
  const parsed = parseFrontmatter(text, rootSkill)
  if (parsed.name !== spec.name) throw new Error(`wrong product name in ${rootSkill}`)
  if (text.split('\n').length > 500) throw new Error(`product router exceeds 500 lines: ${rootSkill}`)
  for (const themeEntry of themes) {
    if (!(await exists(join(directory, 'references', `${themeEntry.key}.md`)))) {
      throw new Error(`missing theme reference: ${spec.id}/${themeEntry.key}`)
    }
  }
  const files = await walk(directory)
  const nestedSkills = files.filter((file) => file !== rootSkill && file.endsWith(`${sep}SKILL.md`))
  if (nestedSkills.length) throw new Error(`nested SKILL.md in ${spec.name}: ${nestedSkills[0]}`)
  for (const file of files.filter((entry) => dirname(entry) === join(directory, 'references') && /\.md$/i.test(entry))) {
    const bytes = (await stat(file)).size
    if (bytes > 100 * 1024) throw new Error(`reference exceeds 100 KiB: ${file} (${bytes} bytes)`)
    if (bytes > 90 * 1024) process.stderr.write(`WARNING: reference is above 90 KiB: ${file} (${bytes} bytes)\n`)
  }
  for (const file of files.filter((entry) => /\.(?:md|mdx)$/i.test(entry))) {
    const body = await readFile(file, 'utf8')
    let fence = null
    for (const line of body.split('\n')) {
      const fenceMatch = line.match(/^\s*(```+|~~~+)/)
      if (fenceMatch) {
        const marker = fenceMatch[1]
        if (!fence) fence = { character: marker[0], length: marker.length }
        else if (fence.character === marker[0] && marker.length >= fence.length) fence = null
        continue
      }
      if (fence) continue
      for (const match of line.matchAll(/https:\/\/[^\s<>"'`)]+/gi)) {
        if (isInsideInlineCode(line, match.index)) continue
        if (containsMutableRepositoryRef(match[0])) {
          throw new Error(`mutable repository reference in generated content: ${file} -> ${match[0]}`)
        }
      }
      for (const match of line.matchAll(/\]\(([^)]+)\)/g)) {
        if (isInsideInlineCode(line, match.index)) continue
        const raw = match[1].trim().replace(/^<|>$/g, '')
        const fragment = raw.includes('#') ? raw.slice(raw.indexOf('#') + 1).split('?')[0] : ''
        let target = raw.split(/[?#]/)[0]
        if (!target || target.startsWith('/') || /^(?:[a-z]+:|#)/i.test(target)) continue
        try {
          target = decodeURIComponent(target)
        } catch {
          throw new Error(`invalid encoded Markdown link: ${file} -> ${match[1]}`)
        }
        const resolved = resolve(dirname(file), target)
        if (!(await exists(resolved))) throw new Error(`broken generated link: ${file} -> ${match[1]}`)
        if (fragment && /\.(?:md|mdx)$/i.test(resolved)) {
          const decodedFragment = decodeURIComponent(fragment)
          const targetBody = await readFile(resolved, 'utf8')
          if (!hasMarkdownFragment(targetBody, decodedFragment)) {
            throw new Error(`broken generated fragment: ${file} -> ${match[1]}`)
          }
        }
      }
    }
  }
}

async function markAtomicsInternal(atomicSkills) {
  for (const source of atomicSkills) {
    let text = source.text
    if (/^  internal:\s*/m.test(text)) text = text.replace(/^  internal:\s*.*$/m, '  internal: true')
    else if (/^metadata:\s*$/m.test(text)) text = text.replace(/^metadata:\s*$/m, 'metadata:\n  internal: true')
    else {
      const end = text.indexOf('\n---', 4)
      if (end < 0) throw new Error(`missing frontmatter terminator: ${source.name}`)
      text = `${text.slice(0, end)}\nmetadata:\n  internal: true${text.slice(end)}`
    }
    await writeFile(source.skillPath, normalizeText(text))
  }
}

async function generatedDirectories() {
  const directories = []
  for (const entry of (await readdir(skillsDir, { withFileTypes: true })).sort((a, b) => ascii(a.name, b.name))) {
    if (!entry.isDirectory()) continue
    const directory = join(skillsDir, entry.name)
    for (const markerName of [productMarker, legacyMarker]) {
      const markerPath = join(directory, markerName)
      if (!(await exists(markerPath))) continue
      const marker = JSON.parse(await readFile(markerPath, 'utf8'))
      if (marker?.generator !== generator || marker?.name !== entry.name) {
        throw new Error(`refusing to replace invalid generated directory: ${directory}`)
      }
      directories.push(directory)
      break
    }
  }
  return directories
}

function buildCatalogFiles(results) {
  const byId = new Map(results.map((result) => [result.spec.id, result.spec]))
  const groupings = categoryGroups.map(([title, ids]) => ({
    title,
    description: `${title} product skills from the official TanStack public catalog.`,
    skills: ids.map((id) => byId.get(id)?.name || (() => { throw new Error(`missing catalog product ${id}`) })()),
  }))
  const skillsSh = {
    $schema: 'https://skills.sh/schemas/skills.sh.schema.json',
    notGrouped: 'bottom',
    groupings,
  }
  const marketplace = {
    name: 'tanstack-skills-extracted',
    description: 'Install one curated product skill for every public TanStack library.',
    owner: { name: 'lukasa1993' },
    plugins: groupings.map((group) => ({
      name: group.title.toLowerCase().replace(/[^a-z0-9]+/g, '-'),
      source: './',
      description: group.description,
      license: 'MIT',
      strict: false,
      skills: group.skills.map((name) => `./skills/${name}`),
    })),
  }
  return { skillsSh, marketplace }
}

async function installStage(stageRoot, results, atomicSkills) {
  const newSkillsDir = join(stageRoot, 'skills')
  const existingGenerated = await generatedDirectories()
  const existingSet = new Set(existingGenerated)
  for (const result of results) {
    const target = join(skillsDir, result.spec.name)
    if ((await exists(target)) && !existingSet.has(target)) {
      throw new Error(`refusing to replace non-generated skill directory: ${target}`)
    }
  }
  const backupRoot = join(root, `.tanstack-product-backup.tmp-${process.pid}`)
  if (await exists(backupRoot)) throw new Error(`refusing to overwrite stale backup: ${backupRoot}`)
  await mkdir(join(backupRoot, 'skills'), { recursive: true })
  await markAtomicsInternal(atomicSkills)
  const installedDirectories = []
  const catalogTargets = [
    [join(root, 'skills.sh.json'), join(backupRoot, 'skills.sh.json')],
    [join(root, '.claude-plugin', 'marketplace.json'), join(backupRoot, 'marketplace.json')],
  ]
  try {
    for (const directory of existingGenerated) {
      await rename(directory, join(backupRoot, 'skills', directory.split(sep).at(-1)))
    }
    for (const [target, backup] of catalogTargets) {
      if (await exists(target)) await rename(target, backup)
    }
    for (const result of results) {
      const target = join(skillsDir, result.spec.name)
      await rename(join(newSkillsDir, result.spec.name), target)
      installedDirectories.push(target)
    }
    await rename(join(stageRoot, 'skills.sh.json'), join(root, 'skills.sh.json'))
    await mkdir(join(root, '.claude-plugin'), { recursive: true })
    await rename(join(stageRoot, 'marketplace.json'), join(root, '.claude-plugin', 'marketplace.json'))
  } catch (error) {
    for (const directory of installedDirectories) {
      if (await exists(directory)) await rm(directory, { recursive: true, force: false })
    }
    for (const directory of existingGenerated) {
      const backup = join(backupRoot, 'skills', directory.split(sep).at(-1))
      if (await exists(backup)) await rename(backup, directory)
    }
    for (const [target, backup] of catalogTargets) {
      if (await exists(target)) await rm(target, { force: false })
      if (await exists(backup)) await rename(backup, target)
    }
    throw error
  } finally {
    if (await exists(backupRoot)) await rm(backupRoot, { recursive: true, force: true })
  }
}

async function main() {
  if (process.argv.length > 2) {
    if (process.argv.length === 3 && ['-h', '--help'].includes(process.argv[2])) {
      process.stdout.write('Usage: node scripts/build-groups.mjs\n')
      return
    }
    throw new Error('Usage: node scripts/build-groups.mjs')
  }
  if (JSON.stringify(productSpecs.map((spec) => spec.id)) !== JSON.stringify(expectedCatalogIds)) {
    throw new Error('product specification order does not match the public catalog')
  }
  const docSources = await readDocSources()
  const atomicSkills = await readAtomicSkills(docSources.docPackageOwners)
  const nonMitAtomics = atomicSkills.filter((source) => source.license.replace(/^['"]|['"]$/g, '') !== 'MIT')
  const nonMitDocuments = docSources.manifest.products.flatMap((entry) =>
    entry.releasePackages.filter((release) => release.license !== 'MIT').map((release) => `${release.name}@${release.version}:${release.license}`))
  if (nonMitAtomics.length || nonMitDocuments.length) {
    throw new Error(`mixed source licenses need an explicit policy: ${[
      ...nonMitAtomics.map((source) => `${source.id}:${source.license}`),
      ...nonMitDocuments,
    ].join(', ')}`)
  }
  const stageRoot = join(root, `.tanstack-product-build.tmp-${process.pid}`)
  if (await exists(stageRoot)) throw new Error(`refusing to overwrite stale stage: ${stageRoot}`)
  await mkdir(join(stageRoot, 'skills'), { recursive: true })
  let installed = false
  try {
    const results = []
    for (const spec of productSpecs) {
      results.push(await buildProduct(spec, atomicSkills, atomicSkills, docSources, join(stageRoot, 'skills')))
    }
    const { skillsSh, marketplace } = buildCatalogFiles(results)
    await writeFile(join(stageRoot, 'skills.sh.json'), json(skillsSh))
    await writeFile(join(stageRoot, 'marketplace.json'), json(marketplace))
    await installStage(stageRoot, results, atomicSkills)
    installed = true
    process.stdout.write(`Built ${results.length} product skills from ${atomicSkills.length} extracted skills and ${docSources.manifest.products.reduce((total, entry) => total + entry.documents.length, 0)} official documents.\n`)
  } finally {
    if (!installed && (await exists(stageRoot))) await rm(stageRoot, { recursive: true, force: true })
    if (installed && (await exists(stageRoot))) await rm(stageRoot, { recursive: true, force: true })
  }
}

main().catch((error) => {
  process.stderr.write(`ERROR: ${error?.stack || error}\n`)
  process.exitCode = 1
})
